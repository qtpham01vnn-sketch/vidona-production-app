// Helper functions for Dynamic Storage & Import/Export
export const getStoredTCCS = (): TCCSBang[] => {
  const data = localStorage.getItem('vidona_tccs_list_v3');
  if (data) {
    try {
      const parsed = JSON.parse(data);
      if (Array.isArray(parsed) && parsed.length >= DANH_MUC_TCCS_41_DEFAULT.length) return parsed;
    } catch (e) {}
  }
  localStorage.setItem('vidona_tccs_list_v3', JSON.stringify(DANH_MUC_TCCS_41_DEFAULT));
  return DANH_MUC_TCCS_41_DEFAULT;
};

export const saveStoredTCCS = (list: TCCSBang[]): void => {
  localStorage.setItem('vidona_tccs_list_v3', JSON.stringify(list));
};

export const addOrUpdateTCCS = (tccsItem: TCCSBang): TCCSBang[] => {
  const list = getStoredTCCS();
  const idx = list.findIndex(t => t.ma_tccs === tccsItem.ma_tccs);
  if (idx >= 0) {
    list[idx] = tccsItem;
  } else {
    list.push(tccsItem);
  }
  saveStoredTCCS(list);
  return list;
};

export const deleteTCCS = (maTccs: string): TCCSBang[] => {
  const list = getStoredTCCS();
  const filtered = list.filter(t => t.ma_tccs !== maTccs);
  saveStoredTCCS(filtered);
  return filtered;
};

export const resetTCCSToDefault = (): TCCSBang[] => {
  saveStoredTCCS(DANH_MUC_TCCS_41_DEFAULT);
  return DANH_MUC_TCCS_41_DEFAULT;
};

export const DANH_MUC_TCCS_41 = getStoredTCCS();
